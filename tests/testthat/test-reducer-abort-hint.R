# M103 -- the reducer-stage degeneracy aborts name a `ci_method` only after
# running that method on the caller's own data.
#
# M93 gave the two `mc_ci()` guards a lazily-evaluated `hint`; the four
# reducer-stage guards had none, so the 2026-08-03 hotfix could only DELETE the
# untrue `ci_method` names from three of them. What this file pins is that the
# names are back and that each one was earned: verified by running the method,
# on the data in hand, at the seed and resample count the caller's own retry
# would use.
#
# The evidence base is `tests/testthat/fixtures/abort-remedy-sweep.tsv`,
# generated by `data-raw/sweep-abort-remedies.R` -- 210 rows, one per
# (guard, dataset, method), of which 26 datasets actually reach their guard.

# --- the sweep's own generators ----------------------------------------------
#
# Copied from the generator script, deliberately: the AC2 table below rebuilds
# each cell's dataset from the fixture's own `generator`/`n_s`/`n_r`/`seed`/
# `trigger` columns and re-derives the verdict. A copy that drifted from the
# script's original would produce different data and therefore different
# verdicts, which is exactly what that test fails on -- the duplication is
# checked, not trusted.

gen_mse0 <- function(n_s, n_r, jitter_sd = 0, seed = 1) {
  set.seed(seed)
  mu <- stats::rnorm(n_s, 0, 3)
  data.frame(
    subject = rep(seq_len(n_s), each = n_r),
    rater = rep(seq_len(n_r), times = n_s),
    score = rep(mu, each = n_r) + stats::rnorm(n_s * n_r, 0, jitter_sd)
  )
}

gen_ssa0 <- function(n_s, n_r, jitter_sd = 0, seed = 1) {
  set.seed(seed)
  profile <- stats::rnorm(n_r, 0, 3)
  data.frame(
    subject = rep(seq_len(n_s), each = n_r),
    rater = rep(seq_len(n_r), times = n_s),
    score = rep(profile, times = n_s) + stats::rnorm(n_s * n_r, 0, jitter_sd)
  )
}

gen_resample_degenerate <- function(n_s, n_r, n_varying = 2L, seed = 1) {
  set.seed(seed)
  mu <- stats::rnorm(n_s, 0, 3)
  score <- rep(mu, each = n_r)
  for (i in seq_len(min(n_varying, n_s))) {
    idx <- ((i - 1) * n_r + 1):(i * n_r)
    score[idx] <- score[idx] + stats::rnorm(n_r, 0, 1)
  }
  data.frame(
    subject = rep(seq_len(n_s), each = n_r),
    rater = rep(seq_len(n_r), times = n_s),
    score = score
  )
}

gen_se_zero <- function(n_s, n_r, seed = 1) {
  data.frame(
    subject = rep(1:3, each = 2),
    rater = rep(1:2, times = 3),
    score = c(-1.5, -0.5, 0, 0, 0.5, 1.5)
  )
}

oneway_ests <- function(k_eff) {
  list(
    icc_estimand(unit = "single", k_eff = k_eff, oneway = TRUE),
    icc_estimand(unit = "average", k_eff = k_eff, oneway = TRUE)
  )
}

# Render a condition's message with the RENDERER pinned, not merely observed: a
# pin that depends on how wide the console happened to be, or on whether cli
# decided the terminal could show `ℹ`, is evidence about the environment
# rather than about the message. Width is fixed so nothing hard-wraps, and the
# bullet is fixed to its ASCII form -- which is what testthat renders anyway, and
# what the expected text below is written in.
abort_message <- function(expr) {
  withr::local_options(cli.width = 10000L, cli.unicode = FALSE)
  e <- suppressWarnings(tryCatch(expr, error = function(e) e))
  expect_s3_class(e, "condition")
  conditionMessage(e)
}

first_line <- function(msg) strsplit(msg, "\n", fixed = TRUE)[[1]][[1]]

# The arguments a bullet PROMISES, read out of the message itself rather than
# written down here. A test that re-runs the author's idea of the promised call
# cannot catch a message that promises something else, which is the whole failure
# mode "the promised call is the verified one" exists to prevent.
promised_args <- function(msg, name) {
  hit <- regmatches(
    msg,
    regexpr(paste0(name, " = [0-9]+"), msg)
  )
  if (!length(hit)) {
    return(NULL)
  }
  as.integer(sub(paste0(name, " = "), "", hit))
}

# The seed a bullet promises, in EITHER form it can take. With no caller seed the
# verification ran under `hint_verify_seed` and the bullet names it as a number;
# with a caller seed it ran under theirs, and the bullet says to run under it
# rather than repeating a value the caller already has. A test that reads only the
# numeric form finds nothing in the second case and re-runs UNSEEDED -- a fresh
# draw, which is the one thing "the promised call is the verified one" exists to
# rule out (M103 review pass 2, G1). So the seed-free form is accepted only when
# the message really does point at the caller's own seed.
promised_seed <- function(msg, caller_seed) {
  named <- promised_args(msg, "seed")
  if (!is.null(named)) {
    return(named)
  }
  expect_match(msg, "run under your", fixed = TRUE)
  caller_seed
}

read_sweep <- function() {
  path <- test_path("fixtures", "abort-remedy-sweep.tsv")
  utils::read.delim(path, comment.char = "#", stringsAsFactors = FALSE)
}

# Rebuild the dataset one fixture row describes. The `trigger` column carries the
# jitter ("exact" / "near") and the resample generator's fixed `n_varying`.
sweep_data <- function(row) {
  switch(
    row$generator,
    gen_mse0 = gen_mse0(
      row$n_s,
      row$n_r,
      jitter_sd = if (grepl("near", row$trigger)) 1e-8 else 0,
      seed = row$seed
    ),
    gen_ssa0 = gen_ssa0(
      row$n_s,
      row$n_r,
      jitter_sd = if (grepl("near", row$trigger)) 1e-8 else 0,
      seed = row$seed
    ),
    gen_resample_degenerate = gen_resample_degenerate(
      row$n_s,
      row$n_r,
      n_varying = 2L,
      seed = row$seed
    ),
    gen_se_zero = gen_se_zero(row$n_s, row$n_r, seed = row$seed),
    stop("unknown generator in the sweep fixture: ", row$generator)
  )
}

# The engine fit `icc()` would hand a guard on this data -- or NULL where this
# platform's glmmTMB dies on the data before any CI-stage guard is reached.
#
# That is not hypothetical, and it is why the tests below fire each guard at its
# OWNING REDUCER rather than through `icc()`, exactly as AC1 already does. On
# `gen_mse0` the Linux and Windows runners raise a raw `NA/NaN gradient
# evaluation` from the point fit while macOS reaches the guard (CI on PR #111,
# 2026-08-05, 5 failures in this file). A test routed through `icc()` on that
# data is therefore evidence about the ENGINE on those platforms and not about
# the guard it names -- it reds where the fit dies, and worse, an assertion that
# a message does NOT contain something passes there for the wrong reason.
engine_or_null <- function(df) {
  suppressWarnings(tryCatch(fit_glmmtmb_oneway(df), error = function(e) NULL))
}

# The hint `icc()` builds for a one-way random call on this data, argument for
# argument with `boundary_hint_for()` in `R/icc.R`. Fired at a reducer this is
# the same promise the dispatch would have passed it, including the engine tier
# when the platform has a fit to give.
icc_hint <- function(
  df,
  invoked,
  engine = engine_or_null(df),
  n_r = 3L,
  seed = 1L,
  boot_samples = 999L
) {
  boundary_method_hint(
    oneway = TRUE,
    multilevel = FALSE,
    replicates = FALSE,
    raters = "random",
    balanced = TRUE,
    type = "agreement",
    type_supplied = FALSE,
    unit = c("single", "average"),
    seed = seed,
    boot_samples = boot_samples,
    mc_samples = 10000L,
    conf_level = 0.95,
    df = df,
    estimands = oneway_ests(n_r),
    n0 = n_r,
    invoked = invoked,
    engine = engine
  )
}

# The bootstrap refit-convergence guard, fired with the engine `icc()` would have
# used -- or, where this platform's fit died on the data, with a refit stub
# returning the all-NA draws such a fit yields. The guard fires on zero converged
# refits either way, which is the condition under test.
fire_bootstrap_guard <- function(
  df,
  hint,
  engine = engine_or_null(df),
  boot_samples = 999L,
  n_r = 3L
) {
  eng <- if (is.null(engine)) {
    list(
      simulate_refit = function(n, seed = NULL) {
        matrix(
          NA_real_,
          nrow = 2L,
          ncol = n,
          dimnames = list(c("subject", "residual"), NULL)
        )
      }
    )
  } else {
    engine
  }
  bootstrap_ci(
    eng,
    oneway_ests(n_r),
    conf_level = 0.95,
    boot_samples = boot_samples,
    seed = 1L,
    hint = hint
  )
}

# --- AC1: every degeneracy guard splices the hint it is handed ----------------

# The six guards, each fired directly at the function that owns it, and each
# handed a hint no verification would ever produce. Firing the OWNER rather than
# `icc()` is deliberate: on some of this data glmmTMB dies with a raw error
# before any CI-stage guard is reached, which would make the test evidence about
# the engine rather than about the guard.
#
# The leading lines are frozen at 703fc1b, the commit that shipped them.
test_that("each of the six degeneracy guards splices a lazily-built hint (AC1)", {
  skip_on_cran()
  synthetic <- c(i = "SYNTHETIC-VERIFIED-BULLET")

  fire <- list(
    list(
      label = "mc_ci: non-finite parameter covariance",
      lead = paste(
        "The Monte-Carlo interval could not be computed: the fitted parameter",
        "covariance is not finite."
      ),
      run = function(hint) {
        rmvn(2L, c(subject = 0), matrix(NA_real_, 1L, 1L), hint = hint)
      }
    ),
    list(
      label = "mc_ci: non-finite draws",
      lead = paste(
        "The Monte-Carlo interval could not be computed: 50% of draws were",
        "non-finite."
      ),
      run = function(hint) {
        mc_interval(
          list(subject = c(1, Inf), residual = c(1, 1)),
          icc_estimand(unit = "single", k_eff = 3, oneway = TRUE),
          hint = hint
        )
      }
    ),
    list(
      label = "bootstrap: refit convergence",
      lead = paste(
        "The bootstrap interval could not be computed: only 0 of 4 refits",
        "converged."
      ),
      run = function(hint) {
        draws <- matrix(
          NA_real_,
          nrow = 2L,
          ncol = 4L,
          dimnames = list(c("subject", "residual"), NULL)
        )
        bootstrap_ci(
          list(simulate_refit = function(n, seed = NULL) draws),
          oneway_ests(3),
          boot_samples = 4L,
          hint = hint
        )
      }
    ),
    list(
      label = "classical: MSE = 0",
      lead = paste(
        "The classical one-way SEARLE exact-F interval is undefined for this",
        "data."
      ),
      run = function(hint) {
        searle_ci(gen_mse0(6, 3), oneway_ests(3), hint = hint)
      }
    ),
    list(
      label = "npbootstrap: observed degeneracy",
      lead = paste(
        "The one-way transformed bootstrap-t interval is undefined for this",
        "data."
      ),
      run = function(hint) {
        npbootstrap_ci(
          gen_ssa0(6, 3),
          oneway_ests(3),
          boot_samples = 99L,
          seed = 1L,
          hint = hint
        )
      }
    ),
    list(
      label = "npbootstrap: degenerate resamples",
      lead = paste(
        "The one-way transformed bootstrap-t interval could not be computed:",
        "128 of 999 resamples were degenerate (SSA = 0 or SE = 0)."
      ),
      run = function(hint) {
        npbootstrap_ci(
          gen_resample_degenerate(30, 2),
          oneway_ests(2),
          boot_samples = 999L,
          seed = 1L,
          hint = hint
        )
      }
    )
  )

  for (site in fire) {
    msg <- abort_message(site$run(synthetic))
    expect_true(grepl("SYNTHETIC-VERIFIED-BULLET", msg, fixed = TRUE))
    expect_identical(first_line(msg), site$lead)

    cnd <- suppressWarnings(tryCatch(
      site$run(character(0)),
      error = function(e) e
    ))
    expect_s3_class(cnd, "intraclass_singular_fit")
    # Without a hint the message is the guard's own text and nothing else.
    expect_false(grepl("SYNTHETIC", conditionMessage(cnd), fixed = TRUE))
  }
})

