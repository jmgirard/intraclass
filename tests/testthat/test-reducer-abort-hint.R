# --- AC3: no guard recommends the method that just failed in it ---------------

test_that("no remedy bullet names the ci_method the caller invoked (AC3)", {
  skip_on_cran()
  # One case per (guard, invoking value). The `gen_ssa0` and resample cases fire
  # through `icc()`, the path a user meets them on. The `gen_mse0` cases cannot:
  # the point fit dies before the guard on some platforms (see `engine_or_null()`
  # above), and an assertion that a message does not name a method would then
  # hold of an engine error rather than of the guard. Those fire at the reducer,
  # handed the hint the dispatch would have built.
  mse0 <- gen_mse0(6, 3)
  cases <- list(
    list(
      method = "bootstrap",
      fire = function() {
        fire_bootstrap_guard(mse0, icc_hint(mse0, "bootstrap"))
      }
    ),
    list(
      method = "searle",
      fire = function() {
        searle_ci(mse0, oneway_ests(3), hint = icc_hint(mse0, "searle"))
      }
    ),
    list(
      method = "burch",
      fire = function() {
        burch_ci(mse0, oneway_ests(3), hint = icc_hint(mse0, "burch"))
      }
    ),
    list(method = "npbootstrap", df = gen_ssa0(6, 3)),
    list(method = "npbootstrap", df = gen_resample_degenerate(30, 2)),
    list(method = "montecarlo", df = gen_ssa0(6, 3))
  )
  for (case in cases) {
    msg <- if (is.null(case$fire)) {
      abort_message(icc(
        case$df,
        score,
        subject,
        rater,
        model = "oneway",
        ci_method = case$method,
        seed = 1L
      ))
    } else {
      abort_message(case$fire())
    }
    # The guard's own leading line is exempt (AC3): `bootstrap_ci()`'s names
    # "bootstrap" by construction, and AC1 freezes it. Everything after it is
    # remedy text.
    remedies <- sub("^[^\n]*\n?", "", msg)
    expect_false(
      grepl(
        paste0("ci_method = \"", case$method, "\""),
        remedies,
        fixed = TRUE
      ),
      info = paste("guard invoked as", case$method)
    )
  }
})

# --- AC4: forcing a hint never re-enters the guard that is forcing it ---------

test_that("verifying burch from a searle abort terminates, not recurses (AC4)", {
  skip_on_cran()
  # `searle_ci()` and `burch_ci()` share `classical_guard_observed()`, so the
  # `searle` abort's own hint runs `burch`, which re-enters that guard. The run
  # carries no hint of its own, so the re-entered guard aborts once and is
  # caught -- one classed condition out, no recursion.
  # Fired at the reducer with the hint the dispatch would have built, so the
  # re-entry is exercised on every platform rather than only where the point fit
  # survives this data (`engine_or_null()` above).
  df <- gen_mse0(6, 3)
  cnd <- suppressWarnings(tryCatch(
    searle_ci(df, oneway_ests(3), hint = icc_hint(df, "searle")),
    error = function(e) e
  ))
  # Reaching this line at all IS the assertion: were the verification run to
  # carry a hint of its own, `searle` would verify `burch`, whose hint would
  # verify `searle`, and the call would never return. What the assertions add is
  # that the one condition to escape is the guard's, raised once.
  expect_s3_class(cnd, "intraclass_singular_fit")
  expect_identical(
    lengths(regmatches(
      conditionMessage(cnd),
      gregexpr("interval is undefined for this data", conditionMessage(cnd))
    )),
    1L
  )
})

test_that("verification passes no hint to any candidate it runs (AC4)", {
  skip_on_cran()
  seen <- list()
  usable_stub <- function() {
    list(
      list(conf.low = 0.1, conf.high = 0.5, std.error = NA_real_),
      list(conf.low = 0.2, conf.high = 0.6, std.error = NA_real_)
    )
  }
  local_mocked_bindings(
    searle_ci = function(df, estimands, conf_level = 0.95, ...) {
      seen[["searle"]] <<- list(...)
      usable_stub()
    },
    burch_ci = function(df, estimands, conf_level = 0.95, ...) {
      seen[["burch"]] <<- list(...)
      usable_stub()
    }
  )
  boundary_method_usable(
    "searle",
    gen_mse0(6, 3),
    oneway_ests(3),
    conf_level = 0.95,
    n0 = 3
  )
  boundary_method_usable(
    "burch",
    gen_mse0(6, 3),
    oneway_ests(3),
    conf_level = 0.95,
    n0 = 3
  )
  # No `hint` argument reaches either reducer at all -- not an empty one, none.
  expect_null(seen[["searle"]]$hint)
  expect_null(seen[["burch"]]$hint)
  expect_false("hint" %in% names(seen[["searle"]]))
  expect_false("hint" %in% names(seen[["burch"]]))
})

# The three shipped messages AC5 freezes, at 703fc1b. The resample guard is
# outside this criterion by construction: `gen_mse0` never reaches it. The
# bootstrap guard reports a glmmTMB CONVERGENCE COUNT, a property of the
# optimizer on this platform's BLAS rather than of the message, so that integer
# alone is normalized on both sides and every other byte is pinned as-is.
normalize_count <- function(x) {
  sub("only [0-9]+ of 999 refits", "only <n> of 999 refits", x)
}

ac5_expected <- list(
  bootstrap = paste0(
    "The bootstrap interval could not be computed: only <n> of 999 refits ",
    "converged.\n",
    "i A refit counts as converged only when every variance component ",
    "it returned is finite.\n",
    "i Inspect the model fit and the data before retrying."
  ),
  searle = paste0(
    "The classical one-way SEARLE exact-F interval is undefined for this ",
    "data.\n",
    "i The F = MSA/MSE pivot is not usable here: MSA = 24.0087, ",
    "MSE = 0.\n",
    "i Inspect the data before retrying."
  ),
  npbootstrap = paste0(
    "The one-way transformed bootstrap-t interval is undefined for this ",
    "data.\n",
    "i The studentized pivot needs a finite log F and a non-zero ",
    "jackknife SE; this data gives log F = Inf and jackknife SE = NaN.\n",
    "i Inspect the data before retrying."
  )
)

# --- AC5: where nothing works, the message is the one that shipped ------------

test_that("no usable candidate leaves the shipped message untouched (AC5)", {
  skip_on_cran()
  # Each guard's `hint` is the REAL one the dispatch would build -- forced, every
  # candidate actually run. It evaluates to nothing on this data because nothing
  # works on it (the sweep's `gen_mse0` cells: 0 usable of every method at all
  # three of these guards). Were verification to accept a method wrongly, a
  # bullet would appear here and these pins would red. Fired at the reducers
  # rather than through `icc()`, which cannot reach them on every platform (see
  # `engine_or_null()`); the end-to-end path is asserted by the companion test
  # below, where the fit survives.
  df <- gen_mse0(6, 3)
  expected <- ac5_expected
  fire <- list(
    bootstrap = function() {
      fire_bootstrap_guard(df, icc_hint(df, "bootstrap"))
    },
    searle = function() {
      searle_ci(df, oneway_ests(3), hint = icc_hint(df, "searle"))
    },
    npbootstrap = function() {
      npbootstrap_ci(
        df,
        oneway_ests(3),
        boot_samples = 999L,
        seed = 1L,
        hint = icc_hint(df, "npbootstrap")
      )
    }
  )
  for (m in names(expected)) {
    expect_identical(
      normalize_count(abort_message(fire[[m]]())),
      expected[[m]],
      info = m
    )
  }
})

test_that("where the fit survives, icc() delivers that same message (AC5)", {
  skip_on_cran()
  # The end-to-end half of the criterion above: on a platform whose glmmTMB
  # survives `gen_mse0`, the message a user actually meets is byte-identical to
  # the one the reducer produced. Where the fit dies first this has nothing to
  # say, and says so rather than passing on an engine error that happens to
  # contain no bullet.
  df <- gen_mse0(6, 3)
  skip_if(
    is.null(engine_or_null(df)),
    "glmmTMB's point fit dies on this data here, before any CI-stage guard"
  )
  for (m in names(ac5_expected)) {
    msg <- abort_message(icc(
      df,
      score,
      subject,
      rater,
      model = "oneway",
      ci_method = m,
      seed = 1L
    ))
    expect_identical(normalize_count(msg), ac5_expected[[m]], info = m)
  }
})

# --- AC3 (cont.): the case self-exclusion is actually load-bearing ------------

test_that("self-exclusion, and not the data, is what silences a method (AC3)", {
  skip_on_cran()
  # Every AC3 case above passes `seed = 1L` and lands on data where the invoked
  # method is not a candidate anyway, so all six stay green with self-exclusion
  # deleted (M103 review, F1). This test isolates the term itself: one dataset,
  # two hints differing ONLY in `invoked`.
  #
  # The case is real rather than contrived. With no caller `seed` the failing run
  # drew from the ambient stream while verification re-runs under the fixed
  # `hint_verify_seed`, so a stochastic method can verify on the very data it
  # just aborted on -- and without the exclusion the message would recommend the
  # call that had just failed.
  set.seed(7)
  n_s <- 12L
  n_r <- 3L
  mu <- stats::rnorm(n_s, 0, 3)
  df <- data.frame(
    subject = rep(seq_len(n_s), each = n_r),
    rater = rep(seq_len(n_r), times = n_s),
    score = rep(mu, each = n_r) + stats::rnorm(n_s * n_r, 0, 1)
  )
  df <- df[-1, ] # unbalanced: the branch where npbootstrap is the candidate
  hint_for <- function(invoked) {
    boundary_method_hint(
      oneway = TRUE,
      multilevel = FALSE,
      replicates = FALSE,
      raters = "random",
      balanced = FALSE,
      type = "agreement",
      type_supplied = FALSE,
      unit = list("single"),
      conf_level = 0.95,
      df = df,
      estimands = oneway_ests(3),
      n0 = 3,
      seed = NULL,
      boot_samples = 99L,
      invoked = invoked,
      # No engine: this isolates tier 1, so the only difference between the two
      # calls is the exclusion.
      engine = NULL
    )
  }
  # Invoked as something else, `npbootstrap` verifies and is named...
  expect_true(any(grepl("npbootstrap", hint_for("montecarlo"), fixed = TRUE)))
  # ...and invoked as itself, on the same data, it is named by nothing. Deleting
  # `!identical(method, invoked)` makes these two calls agree, reddening this.
  expect_length(hint_for("npbootstrap"), 0L)
})

# --- AC8: an abort that names nothing stays as fast as its guard -------------

test_that("aborts that name no method are not slowed by verification (AC8)", {
  skip_on_cran()
  # Verification costs what the method costs, and `bootstrap` costs a refit per
  # resample. Before the screen, `icc(gen_mse0(6,3), ci_method = "searle")` took
  # 25.6 s to print a message with no bullet in it: the classical guard's cheap
  # tier is empty by construction (both classical reducers share one guard on the
  # same `ss`), so every such abort fell through to a full 999-refit bootstrap
  # that could not help either. The screen bounds that.
  df <- gen_mse0(6, 3)
  # The criterion measures `icc()`, so where the point fit dies on this data
  # before any guard there is no degeneracy abort here to time -- and the engine's
  # own error would satisfy both assertions for the wrong reason.
  skip_if(
    is.null(engine_or_null(df)),
    "glmmTMB's point fit dies on this data here, before any CI-stage guard"
  )
  for (m in list("searle", "burch", NULL)) {
    call_args <- list(
      df,
      quote(score),
      quote(subject),
      quote(rater),
      model = "oneway"
    )
    if (!is.null(m)) {
      call_args$ci_method <- m
    }
    elapsed <- system.time({
      msg <- abort_message(do.call(icc, call_args))
    })[["elapsed"]]
    label <- if (is.null(m)) "default" else m
    # It named nothing (no method is usable on this data)...
    expect_false(grepl("ci_method = ", msg, fixed = TRUE), info = label)
    # ...so it must not have paid a full bootstrap to find that out.
    expect_lt(elapsed, 5)
  }
})

# --- AC9: the default call is hinted on the same terms as an opt-in one -------

test_that("the DEFAULT icc() call gets the same verified naming (AC9)", {
  skip_on_cran()
  # The engine-fit tier was withheld from the default path at first, on its cost;
  # the M103 review found that left the plain call silent on exactly the data the
  # milestone exists for, while `bootstrap` returns a usable interval on it.
  df <- gen_ssa0(6, 3)
  msg <- abort_message(icc(df, score, subject, rater, model = "oneway"))
  expect_true(grepl('ci_method = "bootstrap"', msg, fixed = TRUE))
  # `montecarlo` is what aborted, so it is never named here (AC3 holds on the
  # default path too).
  expect_false(grepl('ci_method = "montecarlo"', msg, fixed = TRUE))

  # Run exactly what the message promises, with its own named arguments. This
  # call set no seed, so the verification ran under `hint_verify_seed` and the
  # bullet must name it as a number -- an unseeded retry would draw differently.
  seed <- promised_seed(msg, NULL)
  expect_identical(seed, as.integer(hint_verify_seed))
  fit <- icc(
    df,
    score,
    subject,
    rater,
    model = "oneway",
    ci_method = "bootstrap",
    seed = seed,
    boot_samples = promised_args(msg, "boot_samples")
  )
  est <- fit$estimates
  for (i in seq_len(nrow(est))) {
    expect_true(
      boundary_interval_usable(
        list(conf.low = est$conf.low[i], conf.high = est$conf.high[i]),
        divisor = if (identical(est$index[i], "ICC(1)")) 1 else 3,
        n0 = 3
      ),
      info = est$index[i]
    )
  }
})

# --- AC6: the promised call is the verified one ------------------------------

test_that("the gen_ssa0 abort names bootstrap, and that call delivers (AC6)", {
  skip_on_cran()
  # The motivating case. Before M103 a user on this data was told to inspect it;
  # `bootstrap` returns a usable interval on 4 of 4 such datasets in the sweep.
  df <- gen_ssa0(6, 3)
  msg <- abort_message(icc(
    df,
    score,
    subject,
    rater,
    model = "oneway",
    ci_method = "npbootstrap",
    seed = 1L
  ))
  expect_true(grepl("ci_method = \"bootstrap\"", msg, fixed = TRUE))

  # ...and the promise is kept: the same call on the same data, at the seed AND
  # resample count the message itself promises, returns intervals
  # `boundary_interval_usable()` accepts. The caller set a seed here, so the
  # promised seed is theirs and the bullet names no number -- reading only a
  # number would re-run this unseeded.
  seed <- promised_seed(msg, 1L)
  expect_identical(seed, 1L)
  expect_null(promised_args(msg, "seed"))
  fit <- icc(
    df,
    score,
    subject,
    rater,
    model = "oneway",
    ci_method = "bootstrap",
    seed = seed,
    boot_samples = promised_args(msg, "boot_samples")
  )
  est <- fit$estimates
  for (i in seq_len(nrow(est))) {
    expect_true(
      boundary_interval_usable(
        list(conf.low = est$conf.low[i], conf.high = est$conf.high[i]),
        divisor = if (identical(est$index[i], "ICC(1)")) 1 else 3,
        n0 = 3
      ),
      info = est$index[i]
    )
  }
})

test_that("an engine-fit bullet promises a readable seed in both forms (AC6)", {
  skip_on_cran()
  # The two forms the promise can take, pinned so neither can quietly become
  # unreadable. Whichever it is, a reader must be able to reconstruct the seed the
  # verification ran under; a bullet naming no number AND not pointing at the
  # caller's own seed promises a call nobody can reproduce.
  df <- gen_ssa0(6, 3)
  abort_at <- function(...) {
    abort_message(icc(
      df,
      score,
      subject,
      rater,
      model = "oneway",
      ci_method = "npbootstrap",
      ...
    ))
  }
  seeded <- abort_at(seed = 7L)
  # The caller's own seed is what ran, so the bullet points at it rather than
  # repeating the value...
  expect_match(seeded, "run under your", fixed = TRUE)
  expect_null(promised_args(seeded, "seed"))
  expect_identical(promised_seed(seeded, 7L), 7L)
  # ...and with no caller seed the fixed verification seed is named as a number.
  unseeded <- abort_at()
  expect_identical(promised_seed(unseeded, NULL), as.integer(hint_verify_seed))
})

test_that("a two-method engine bullet says whose resample count it names", {
  # Both engine-fit methods usable at once: the bullet then describes TWO runs,
  # and `boot_samples` belongs to only one of them -- `montecarlo` takes none at
  # all. Built directly, because the sweep's data never makes both usable where
  # tier 1 has already failed.
  both <- boundary_engine_hint(
    usable = function(m) TRUE,
    contrast = "the default",
    seed = NULL,
    boot_samples = 999L
  )
  expect_length(both, 1L)
  expect_match(both, "Both runs used", fixed = TRUE)
  expect_match(both, "the bootstrap at", fixed = TRUE)
  expect_match(both, "reproduce them", fixed = TRUE)
  # One method named, one run: the singular wording, and the count reads as its
  # own without needing an owner.
  one <- boundary_engine_hint(
    usable = function(m) identical(m, "bootstrap"),
    contrast = "the default",
    seed = NULL,
    boot_samples = 999L
  )
  expect_match(one, "That run used", fixed = TRUE)
  expect_match(one, "and {.code boot_samples = 199}", fixed = TRUE)
  # And with the caller's own seed, both forms point back at it rather than
  # naming a number.
  expect_match(
    boundary_engine_hint(function(m) TRUE, "the default", seed = 3L),
    "both run under your",
    fixed = TRUE
  )
})
